"""Render every per-suite results table to results/report_tables.md (mean ± sd over seeds).

Re-run after any suite finishes; docs/experiment_report.md quotes these tables.

    uv run python -m experiments.decompose
    uv run python -m experiments.select
    uv run python -m experiments.report_tables
"""

from __future__ import annotations

import pandas as pd

from experiments.run import RESULTS_DIR
from experiments.run_suite import write_summary

SUITE_ORDER = (
    "models",
    "factors",
    "neutral",
    "objective",
    "lookback",
    "epochs",
    "protocol",
    "architecture",
    "final",
    "ensemble",
    "full_probe",
    "full_paper",
    "full_paper_costs",
    "full_recipe",
    "full_bench",
)
COLUMNS = {
    "sharpe": "SR",
    "hac_t_stat": "HAC t",
    "mean_return": "μ",
    "volatility": "σ",
    "max_drawdown": "MDD",
    "turnover": "turnover",
    "net_exposure": "net exp",
    "sharpe_neutral": "SR neutral part",
    "net_sharpe": "SR net",
}


PERCENT = {"mean_return", "volatility", "max_drawdown"}
WITH_SEED_SD = {"sharpe", "net_sharpe"}


def _cell(values: pd.Series, column: str) -> str:
    mean = values.mean()
    if pd.isna(mean):
        return "–"
    text = f"{mean:.1%}" if column in PERCENT else f"{mean:.2f}"
    if column in WITH_SEED_SD and values.count() > 1:
        text += f" ± {values.std():.2f}"
    return text


def markdown_table(frame: pd.DataFrame) -> str:
    header = "| " + " | ".join(map(str, frame.columns)) + " |"
    rule = "|" + "---|" * len(frame.columns)
    body = [
        "| " + " | ".join(map(str, row)) + " |" for row in frame.itertuples(index=False)
    ]
    return "\n".join([header, rule, *body])


def suite_table(frame: pd.DataFrame, suite: str) -> str:
    grouped = frame[frame.suite == suite].groupby("variant", sort=False)
    order = grouped["sharpe"].mean().sort_values(ascending=False).index
    rows = []
    for variant in order:
        group = grouped.get_group(variant)
        rows.append(
            {"variant": variant, "n": len(group)}
            | {label: _cell(group[column], column) for column, label in COLUMNS.items()}
        )
    return markdown_table(pd.DataFrame(rows))


def main() -> None:
    summary = write_summary()
    decomposition = pd.read_csv(RESULTS_DIR / "decomposition.csv")[
        ["run", "sharpe_neutral"]
    ]
    frame = summary.merge(decomposition, on="run", how="left")
    period = f"{frame.start_date.min()} → {frame.end_date.max()}"
    parts = [
        "# Results tables (auto-generated by `experiments.report_tables`)",
        "",
        f"OOS window of rolling runs: {period}. Mean over seeds; `±` = seed sd. "
        "SR net uses the paper cost model (5 bp × turnover + 1 bp × short). "
        "`SR neutral part` = Sharpe of the dollar-neutral component (see `experiments/decompose.py`).",
    ]
    for suite in SUITE_ORDER:
        if (frame.suite == suite).any():
            parts += ["", f"## {suite}", "", suite_table(frame, suite)]
    selection_path = RESULTS_DIR / "selection.csv"
    if selection_path.exists():
        selection = pd.read_csv(selection_path)
        admissible = selection[
            (~selection.duplicate_of_earlier) & (selection.net_exposure.abs() < 0.05)
        ]
        ensembles = admissible[admissible.suite == "ensemble"].sort_values(
            "sel_net_sharpe", ascending=False
        )
        columns = [
            "run",
            "sel_sharpe",
            "sel_net_sharpe",
            "hold_sharpe",
            "hold_net_sharpe",
            "hold_turnover",
        ]
        parts += [
            "",
            "## Selection (2020-02 → 2022-12) vs holdout (2023-01 → 2025-12), dollar-neutral ensembles",
            "",
            markdown_table(ensembles[columns].round(2)),
        ]
    (RESULTS_DIR / "report_tables.md").write_text("\n".join(parts) + "\n")
    print(f"Wrote {RESULTS_DIR / 'report_tables.md'}")


if __name__ == "__main__":
    main()
